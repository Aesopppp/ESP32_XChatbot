"""重新生成 VoCat 菜单的小字库；常规固件构建直接使用已提交的 C 文件。

需要 Node.js/npx；字体来自 LVGL 附带的思源黑体，遵循 SIL OFL 1.1。
只生成菜单字形和可打印 ASCII，不随固件打包完整的字体源文件。
"""

from pathlib import Path
import re
import shutil
import subprocess
import tempfile


def main():
    root = Path(__file__).resolve().parents[1]
    board = root / "main/boards/espressif/esp-vocat"
    source = (board / "vocat_settings_display.cc").read_text(encoding="utf-8")
    literals = re.findall(r'"([^"\n]*)"', source)
    chinese = "".join(sorted({c for s in literals for c in s if ord(c) > 127}))
    font_dir = root / "managed_components/lvgl__lvgl/scripts/built_in_font"
    npx = shutil.which("npx.cmd") or shutil.which("npx")
    if not npx:
        raise SystemExit("请先安装 Node.js (包含 npx)")
    with tempfile.TemporaryDirectory(prefix="vocat-menu-font-") as temp:
        output = Path(temp) / "vocat_menu_font_20.c"
        subprocess.run([
            npx, "--yes", "lv_font_conv@1.5.3", "--font",
            str(font_dir / "SourceHanSansSC-Normal.otf"), "--size", "20",
            "--bpp", "4", "--format", "lvgl", "--no-compress", "--no-kerning",
            "--range", "0x20-0x7e", "--symbols", chinese, "--output", str(output),
        ], check=True)
        data = output.read_text(encoding="utf-8")
        # 去掉生成器记录的本机临时路径，保证不同机器生成相同源文件。
        data = re.sub(r" \* Opts:.*", " * Generated by scripts/generate_vocat_menu_font.py", data)
        (board / "vocat_menu_font_20.c").write_text(
            '// 思源黑体菜单子集；许可证见 vocat_menu_font_LICENSE.txt。\n'
            '#include "sdkconfig.h"\n#if CONFIG_USE_EMOTE_MESSAGE_STYLE\n'
            + data + '\n#endif\n', encoding="utf-8", newline="\n"
        )
    shutil.copyfile(font_dir / "font_license/SourceHanSansSC/LICENSE.txt",
                    board / "vocat_menu_font_LICENSE.txt")
    print(f"Generated menu font: ASCII + {len(chinese)} Chinese/punctuation glyphs")


if __name__ == "__main__":
    main()
